/**
 * Merges published reserved-username lists into the API's table of handles no one can take
 * (domain-model §1.6). Comment lines (`#`) are skipped, underscores become hyphens (handles
 * have no underscores, and `sign_in` should reserve `sign-in`), and names that couldn't be a
 * handle anyway (wrong characters or length) are left out and listed in the report.
 */

/** A published list, pinned to a commit (docs/license-evidence/{evidence}). */
export interface ReservedList {
  title: string;
  repository: string;
  commit: string;
  evidence: string;
  /** The list file: one name per line. */
  text: string;
  /** The LICENSE file, carried with the generated table as MIT asks. */
  license: string;
}

/** The pinned lists, under /source-texts. */
export const LISTS = [
  {
    title: "The Big Username Blocklist",
    repository: "https://github.com/marteinn/The-Big-Username-Blocklist",
    commit: "c5d456f6af0285931c85e08d53ed7e1ac35d31fc",
    evidence: "big-username-blocklist",
    file: "big-username-blocklist/list_raw.txt",
    licenseFile: "big-username-blocklist/LICENSE",
  },
  {
    title: "shouldbee/reserved-usernames",
    repository: "https://github.com/shouldbee/reserved-usernames",
    commit: "0302214e8c1363fc5877ce3343ef6262e8852e96",
    evidence: "shouldbee-reserved-usernames",
    file: "shouldbee-reserved-usernames/reserved-usernames.txt",
    licenseFile: "shouldbee-reserved-usernames/LICENSE",
  },
] as const;

/** The handle syntax (domain-model §1.6; apps/api `Handle`). */
const HANDLE = /^[a-z0-9](?:[a-z0-9-]{1,28})[a-z0-9]$/;

export function generate(lists: readonly ReservedList[]): { module: string; report: string } {
  const names = new Set<string>();
  const report: string[] = [];
  for (const list of lists) {
    const entries = list.text
      .split(/\r?\n/)
      .map((l) => l.trim().toLowerCase())
      .filter((l) => l !== "" && !l.startsWith("#"))
      .map((l) => l.replaceAll("_", "-"));
    const skipped = entries.filter((n) => !HANDLE.test(n) || n.includes("--"));
    for (const n of entries) if (!skipped.includes(n)) names.add(n);
    report.push(
      `${list.title}: ${entries.length} names, ${skipped.length} left out (not a possible handle)${skipped.length ? `: ${skipped.join(", ")}` : ""}`,
    );
  }
  const sorted = [...names].sort();
  report.push(`Merged: ${sorted.length} names.`);

  const notices = lists
    .map(
      (l) =>
        ` * ${l.title}, ${l.repository}/tree/${l.commit}\n * (docs/license-evidence/${l.evidence}):\n *\n${l.license
          .trimEnd()
          .split("\n")
          .map((line) => (line ? ` *   ${line}` : " *"))
          .join("\n")}`,
    )
    .join("\n *\n");
  const module = `// cspell:disable -- third-party word lists
/**
 * Generated by tools/source-conversion (\`pnpm reserved-names\`). Do not edit.
 *
 * Service and system names no one can take as a handle, merged from these lists (MIT). Changes:
 * underscores written as hyphens, and names that couldn't be a handle left out.
 *
${notices}
 */

export const generalReservedNames: readonly string[] = [
${sorted.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
];
`;
  return { module, report: `${report.join("\n")}\n` };
}
