/**
 * Builds the list of country codes from Unicode CLDR's territory data (docs/license-evidence/
 * unicode-cldr). `territoryInfo` lists every territory CLDR has data for, as ISO 3166-1 alpha-2
 * codes, with Kosovo's user-assigned `XK`. Left out, and named in the report:
 *
 * - `ZZ`, CLDR's "unknown region";
 * - the codes ISO only reserves "exceptionally" (Ascension Island, Clipperton Island, Diego Garcia,
 *   Ceuta and Melilla, the Canary Islands, Tristan da Cunha, Sark): they aren't ISO 3166-1 entries,
 *   and the people living there choose the country they belong to.
 *
 * CLDR has already left out its deprecated codes (the former Yugoslavia, Zaire …) and groupings
 * (EU, UN …); the report checks that against its containment table.
 */

/** Codes ISO reserves exceptionally, not part of ISO 3166-1. */
export const EXCEPTIONAL = ["AC", "CP", "CQ", "DG", "EA", "IC", "TA"] as const;

export interface CountrySource {
  /** `territoryInfo.json` */
  info: string;
  /** `territoryContainment.json` */
  containment: string;
  /** The `LICENSE` file, carried with the generated list as the Unicode License asks. */
  license: string;
}

interface TerritoryInfoFile {
  supplemental: { territoryInfo: Record<string, unknown> };
}
interface ContainmentFile {
  supplemental: { territoryContainment: Record<string, { _contains?: string[] }> };
}

export function generate({ info, containment, license }: CountrySource): {
  module: string;
  report: string;
} {
  const known = Object.keys((JSON.parse(info) as TerritoryInfoFile).supplemental.territoryInfo);
  const groups = Object.entries(
    (JSON.parse(containment) as ContainmentFile).supplemental.territoryContainment,
  )
    .filter(([code]) => /^[A-Z]{2}$/.test(code))
    .map(([code]) => code);
  const left = new Set<string>(["ZZ", ...EXCEPTIONAL]);
  const codes = known.filter((c) => /^[A-Z]{2}$/.test(c) && !left.has(c)).sort();
  const grouped = codes.filter((c) => groups.includes(c));
  if (grouped.length > 0) throw new Error(`Groupings among the countries: ${grouped.join(", ")}`);
  const notice = license
    .trim()
    .split("\n")
    .map((l) => (l === "" ? " *" : ` *   ${l}`))
    .join("\n");
  const module = `/**
 * Generated by tools/source-conversion (\`pnpm countries\`). Do not edit.
 *
 * The country codes: ISO 3166-1 alpha-2, and Kosovo's \`XK\`, from the territory data of the Unicode
 * Common Locale Data Repository (CLDR), release 49 (docs/license-evidence/unicode-cldr). Left out:
 * ZZ (unknown) and ${EXCEPTIONAL.join(", ")} (ISO reserves them, but they aren't country entries).
 *
 * cldr-json, https://github.com/unicode-org/cldr-json/tree/a4b67247b446fd51b475991017a2481911210c60:
 *
${notice}
 */
export const COUNTRY_CODES = [
${codes.map((c) => `  "${c}",`).join("\n")}
] as const;
`;
  return {
    module,
    report: `${codes.length} country codes. Left out: ZZ, ${EXCEPTIONAL.join(", ")}. CLDR's other codes (deprecated, groupings) aren't in its territory data.\n`,
  };
}

/** The pinned files, under /source-texts. */
export const CLDR = {
  info: "unicode-cldr/territoryInfo.json",
  containment: "unicode-cldr/territoryContainment.json",
  license: "unicode-cldr/LICENSE",
} as const;
