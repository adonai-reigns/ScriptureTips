/**
 * Generates the versification package's mapping tables from TVTMS: one TypeScript module per
 * scheme, and a report of the rows skipped and the conflicts resolved.
 */

import { BOOKS, formatOsisRef } from "@scripturetips/passage";
import { compose, type Pair } from "./compose.ts";
import { parseTvtms } from "./parse.ts";

export const TVTMS_COMMIT = "be4191f0082aeedddb0eff0c02c966292b2bd641";

/** The schemes generated, each from one TVTMS tradition. */
export const SCHEMES = [
  { id: "kjv", tradition: "Eng-KJV", groups: ["ot", "nt", "additional"] },
  { id: "hebrew", tradition: "Hebrew", groups: ["ot"] },
  { id: "latin", tradition: "Latin", groups: ["ot", "nt", "additional"] },
  { id: "greek", tradition: "Greek", groups: ["ot", "nt", "additional"] },
] as const;

/** File name → content, for `packages/versification/src/data`. */
export function generate(tvtms: string): Map<string, string> {
  const files = new Map<string, string>();
  const { rows, skipped } = parseTvtms(tvtms);
  const report = [`TVTMS import, commit ${TVTMS_COMMIT}`, `${rows.length} rows read`, ""];
  report.push("Rows skipped:");
  for (const [reason, { count, example }] of skipped)
    report.push(`  ${count}  ${reason}: ${example}`);

  for (const scheme of SCHEMES) {
    const groups: readonly string[] = scheme.groups;
    const books = new Set(BOOKS.filter((b) => groups.includes(b.group)).map((b) => b.osis));
    const { pairs, conflicts } = compose(rows, scheme.tradition, books);
    files.set(`${scheme.id}.ts`, moduleFor(scheme.id, scheme.tradition, pairs));
    report.push("", `${scheme.id} (${scheme.tradition}): ${pairs.length} pairs`);
    for (const c of conflicts) report.push(`  conflict: ${c}`);
  }
  files.set("import-report.txt", `${report.join("\n")}\n`);
  return files;
}

function moduleFor(id: string, tradition: string, pairs: readonly Pair[]): string {
  const ref = (r: Pair[number]) => (r ? `"${formatOsisRef(r)}"` : "null");
  const lines = pairs.map(([s, c]) => `  [${ref(s)}, ${ref(c)}],`);
  return `/**
 * Generated by tools/source-conversion (\`pnpm tvtms\`). Do not edit.
 *
 * Versification data from STEP Bible (https://www.STEPBible.org), based on work at Tyndale House
 * Cambridge, CC BY 4.0: TVTMS, https://github.com/STEPBible/STEPBible-Data/tree/${TVTMS_COMMIT}
 *
 * Changes: the "${tradition}" tradition's mapping to the KJV standard, composed with the canonical
 * scheme's (domain-model.md §2.1), and reformatted as pairs of OSIS references. The data itself
 * is unchanged. See CHANGES.md.
 *
 * Each pair is [${id} verse, canonical verse]; null means no counterpart. A verse in no pair has
 * the same number in both.
 */

import type { MappingPairs } from "../mapping.ts";

export const pairs: MappingPairs = [${lines.length ? `\n${lines.join("\n")}\n` : ""}];
`;
}
